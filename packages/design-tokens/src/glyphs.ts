export type KindGlyph = keyof typeof K16;
export type SmallKindGlyph = keyof typeof K8;
export type StateGlyph = keyof typeof S8;
export type ActionGlyph = keyof typeof U16;
export type GlyphName = KindGlyph | SmallKindGlyph | StateGlyph | ActionGlyph;

export const GLYPHS: Record<GlyphName, readonly string[]> = { ...K16, ...K8, ...S8, ...U16 };

/** Side of a glyph in picture pixels: 16 for kinds and actions, 8 for states. */
export function glyphSize(name: GlyphName): number {
  return GLYPHS[name].length;
}

/** The glyph as an SVG of squares, one rect per run of set pixels. */
/** A glyph as SVG: black for a mask, or in `fill` for a background. */
export function glyphSvg(name: GlyphName, fill?: string): string {
  const rows = GLYPHS[name];
  const n = rows.length;
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let end = x;
      while (row[end] === '#') end++;
      rects += `<rect x="${x}" y="${y}" width="${end - x}" height="1"/>`;
      x = end;
    }
  });
  const paint = fill ? ` fill="${fill}"` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges"${paint}>${rects}</svg>`;
}

/** `url("data:…")` for CSS masks, or a coloured background with `fill`. */
export function glyphUrl(name: GlyphName, fill?: string): string {
  return `url("data:image/svg+xml,${encodeURIComponent(glyphSvg(name, fill))}")`;
}
