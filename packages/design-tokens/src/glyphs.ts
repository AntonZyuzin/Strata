export type KindGlyph = keyof typeof K16;
export type StateGlyph = keyof typeof S8;
export type GlyphName = KindGlyph | StateGlyph;

export const GLYPHS: Record<GlyphName, readonly string[]> = { ...K16, ...S8 };

/** Side of a glyph in picture pixels: 16 for kinds, 8 for states. */
export function glyphSize(name: GlyphName): number {
  return GLYPHS[name].length;
}

/** The glyph as an SVG of squares, one rect per run of set pixels. */
export function glyphSvg(name: GlyphName): string {
  const rows = GLYPHS[name];
  const n = rows.length;
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let end = x;
      while (row[end] === '#') end++;
      rects += `<rect x="${x}" y="${y}" width="${end - x}" height="1"/>`;
      x = end;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges">${rects}</svg>`;
}

/** `url("data:…")` for CSS masks. */
export function glyphUrl(name: GlyphName): string {
  return `url("data:image/svg+xml,${encodeURIComponent(glyphSvg(name))}")`;
}
